import type { Product } from "./model";
export function draftPatientDescription(p: Pick<Product, "name">) {
  const n = p.name
    .replace(/\[EVENT\]\s*/g, "")
    .replace(/ · (?:원내 수가|정가|상세표)/g, "");
  let text = "",
    focus = "시술 목적·표현과 실제 제공 구성을 확인해주세요.";
  const tail = "피부 상태와 시술 부위에 맞는 진행 계획을 상담에서 안내합니다.";
  if (/닥터플랜/.test(n))
    text = `${n.split(" · ")[1]} 고민을 중심으로 진료 후 시술 계획을 정하는 맞춤 프로그램입니다.\n필요한 시술과 횟수는 상담에서 함께 확인합니다.`;
  else if (/리팟/.test(n))
    text = /트리플|집중케어/.test(n)
      ? `리팟레이저와 재생주사·사후 관리로 구성된 흑자 관리 프로그램입니다.\n시술 부위와 추가 관리 구성은 진료 후 안내합니다.`
      : `흑자 부위에 대한 리팟레이저 시술을 상담하는 상품입니다.\n병변의 크기와 상태를 확인한 뒤 시술 범위를 안내합니다.`;
  else if (/실리프팅|^이마 \d단계|^이중턱 \d단계|모노실/.test(n)) {
    text = `${n.replace(/\([^)]*\)/g, "").trim()} 상품으로, 부위와 단계에 따라 실 구성을 선택합니다.\n사용할 실의 종류와 개수, 시술 범위는 진료 후 확인합니다.`;
    focus = "단계별 실 종류·줄 수와 적용 부위 확인";
  } else if (/선상흉터|패인흉터|국소파인흉터/.test(n))
    text = `흉터 부위에 대한 진피재생 시술 프로그램입니다.\n진료 후 트리덤·쥬브젠 시술과 보완시술의 진행 계획을 안내합니다.`;
  else if (/눈밑동안/.test(n))
    text = `트라이덤과 울트라콜200을 구성으로 하는 ${n} 프로그램입니다.\n눈밑 상태에 맞춰 단계와 진행 횟수를 상담합니다.`;
  else if (/이마주름|팔자주름|미간주름|목 가로주름/.test(n))
    text = `${n.split(" · ")[0]} 부위의 주름을 상담하는 시술 프로그램입니다.\n단가표에 안내된 실 시술·진피재생 시술 중 해당 구성을 진료 후 확인합니다.`;
  else if (/목 탄력저하/.test(n))
    text =
      "목 탄력 고민을 상담하는 에어다이섹터 피코 프로그램입니다.\n목 피부 상태와 시술 범위를 진료 후 확인합니다.";
  else if (/레스틸렌|벨로테로|엘라비에|에피티크/.test(n))
    text = `${n} 필러 상품입니다.\n원하는 부위와 볼륨을 상담하고 사용할 제품·용량을 확인합니다.`;
  else if (/오타모반/.test(n))
    text = `${n.split(" · ")[1].replace(/\([^)]*\)/g, "")} 부위의 오타모반을 상담하는 시술입니다.\n병변의 면적과 상태를 확인한 뒤 시술 범위와 횟수를 안내합니다.`;
  else if (/루비스타/.test(n)) {
    text =
      "병변의 크기에 따라 선택하는 루비스타 시술 상품입니다.\n시술 대상과 적용 범위는 진료 후 확인합니다.";
    focus = "루비스타의 정확한 적응증·장비 명칭 확인";
  } else if (/제모/.test(n))
    text =
      "남성 하관 부위의 털을 대상으로 하는 제모 상품입니다.\n털의 분포와 피부 상태를 확인하고 시술 부위·횟수를 상담합니다.";
  else if (/위고비|마운자로/.test(n)) {
    text = `체중 관리 진료에서 ${n.split(" · ")[0]} 처방 여부를 상담하는 상품입니다.\n사용 가능 여부와 진행 계획은 진료 후 안내합니다.`;
    focus = "처방 상품의 환자용 안내 표현 확인";
  } else if (/Cd\./.test(n)) {
    text =
      "체중 관리 진료에서 주사 시술 여부를 상담하는 상품입니다.\n정확한 주사 종류와 진행 계획은 진료 후 안내합니다.";
    focus = "우선 확인: Cd 약어의 의미·주사명·성분 (임의 추정하지 않음)";
  } else if (/탈모/.test(n))
    text = `${n.replace("[탈모] ", "")}으로, 두피 관리와 단가표에 안내된 주차별 시술을 함께 상담합니다.\n두피 상태에 맞는 관리 구성과 진행 일정을 확인합니다.`;
  else if (/문신제거/.test(n))
    text = `${n} 상품입니다.\n문신의 색·크기·상태를 확인한 뒤 시술 범위와 횟수를 안내합니다.`;
  else if (/초음파 진단/.test(n))
    text =
      "내성발톱·양성종양 제거 관련 진료에서 초음파 검사를 상담하는 항목입니다.\n검사 필요 여부와 범위는 의료진이 진료 후 안내합니다.";
  else if (/MD크림|MD로션/.test(n))
    text = `${n}은 건조·보습 및 피부염 고민으로 상담할 수 있는 제품입니다.\n피부 상태에 맞는 사용 여부와 방법을 안내받으세요.`;
  else if (/내맘대로/.test(n)) {
    text =
      "피부 상태에 맞춰 원하는 관리 항목을 선택하는 프로그램입니다.\n관리 종류에 따라 차감 횟수가 다르므로 선택 전에 구성을 확인합니다.";
    focus = "선택 가능한 관리와 차감 기준 확인";
  } else if (/IVNT/.test(n))
    text =
      "정맥 내 영양요법을 상담하는 상품으로, 백옥주사·신데렐라주사 항목을 안내합니다.\n건강 상태와 복용 중인 약 등을 확인한 뒤 적용 여부를 결정합니다.";
  else if (/이마 히알라제/.test(n)) {
    text =
      "이마 부위의 히알라제 주사를 상담하는 상품입니다.\n기존 시술 이력과 현재 상태를 진료 후 확인합니다.";
    focus = "적용 가능한 필러와 시술 범위 확인";
  } else if (/보톡스/.test(n)) {
    text = `${n} 상품입니다.\n적용 부위와 용량은 진료 후 확인하며, 선택한 옵션의 제품 구성을 안내합니다.`;
    focus = "보톡스 부위·용량·제품 구성이 상품명과 일치하는지 확인";
  } else if (/슈링크|인모드|리프테라|다이아리프팅/.test(n))
    text = `${n} 구성으로 상담하는 시술 상품입니다.\n얼굴 상태와 원하는 부위를 확인하고 시술 범위를 안내합니다.`;
  else if (
    /네오빔|셀렉아크네|골드 PTT|클라리티2|V-laser|여드름|트러블관리/.test(n)
  )
    text = `${n.replace("피지선 박멸", "피지·").replace(" · 상세표", "")} 구성의 시술 상품입니다.\n현재 피부 상태를 확인하고 적합한 시술 범위와 횟수를 안내합니다.`;
  else if (/포텐자|프락셀|실펌|피코MLA/.test(n))
    text = `${n} 구성의 시술 상품입니다.\n시술 부위와 피부 상태를 확인한 뒤 적용 범위와 진행 계획을 상담합니다.`;
  else if (
    /엑소좀|진피재생|쥬베룩|물광주사|기미주사|새살주사|연어주사|리쥬란/.test(n)
  )
    text = `${n} 시술을 상담하는 상품입니다.\n${tail}`;
  else if (/프리미엄 라라관리/.test(n))
    text =
      "라라필·LDM·매뉴얼 마사지·LED·모델링팩으로 구성된 피부관리 상품입니다.\n피부 상태에 맞는 관리 진행을 상담합니다.";
  else if (/재생\/장벽|재생\/진정/.test(n))
    text = `${n}로, 회차별로 정해진 피부관리 구성을 이용하는 프로그램입니다.\n피부 상태를 확인하고 관리 순서와 일정을 안내합니다.`;
  else if (/아쿠아필|라라필|크라이오|LDM|이온토|고주파 관리/.test(n))
    text = `${n} 구성의 피부관리 상품입니다.\n피부 상태와 원하는 관리 목적에 맞춰 진행 여부와 횟수를 상담합니다.`;
  else {
    text = `${n} 구성을 상담하는 상품입니다.\n진료 후 적용 여부와 진행 계획을 안내합니다.`;
    focus = "자동 작성: 시술 목적과 실제 구성을 확인해주세요.";
  }
  return { text, focus };
}
