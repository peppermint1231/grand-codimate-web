export function precautionFor(key: string | undefined): Precaution | undefined {
  return key ? consentPrecautions[key] || contractPrecautions[key] : undefined;
}
export function supplementConsentBody(key: string, body: string): string {
  const spec = precautionFor(key);
  if (!spec) return body;
  const heading = contractPrecautions[key]
    ? "추가 이용 기준 확인"
    : PRECAUTION_HEADING;
  if (body.includes(heading)) return body;
  const addition = `${heading}\n${spec.body}\n[병원 확인: ${PRECAUTION_REVIEW_TOPIC}]`;
  const boundary = /\n\n6\. 환자의 선택/;
  return boundary.test(body)
    ? body.replace(boundary, `\n\n${addition}\n\n6. 환자의 선택`)
    : `${body}\n\n${addition}`;
}
