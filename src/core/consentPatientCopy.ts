export function patientConsentBody(body: string): string {
  let next = body;
  for (const [from, to] of edits) next = next.replaceAll(from, () => to);
  for (const text of removedParagraphs) {
    next = next
      .split("\n")
      .filter((line) => line.replace(/^\d+\)\s*/, "").trim() !== text)
      .join("\n");
  }
  next = next.replace(
    /\n*\[병원 확인: 세부 주의사항의 원문 기준·기간·예외 확인\]/g,
    "",
  );
  // Keep the numbered detail list contiguous after removing former common clauses.
  const start = next.indexOf("5-1. 시술별 세부 주의사항");
  if (start >= 0) {
    const end = next.indexOf("\n\n6. ", start);
    const tail = end < 0 ? "" : next.slice(end);
    let index = 0;
    next =
      next.slice(0, start) +
      next
        .slice(start, end < 0 ? undefined : end)
        .replace(/^\d+\) /gm, () => `${++index}) `) +
      tail;
  }
  return next.replace(/\n{3,}/g, "\n\n").trim();
}
